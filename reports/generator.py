"""
AI AYFAM - Report Generator
مولّد تقارير الأمن السيبراني
"""

import json
import os
from datetime import datetime
from pathlib import Path


def _sev_icon(sev):
    return {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🔵", "info": "⚪"}.get(sev.lower(), "•")


def generate_markdown_report(
    scan_results: dict,
    hostname: str = "unknown",
    language: str = "ar",
) -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    risk = scan_results.get("risk", {})
    all_findings = scan_results.get("findings", [])
    sections = scan_results.get("sections", {})

    counts = risk.get("counts", {})
    score = risk.get("score", 0)
    level_label = risk.get("label_ar" if language == "ar" else "label_en", "UNKNOWN")

    if language == "ar":
        report = f"""# 🛡️ تقرير AI AYFAM للأمن السيبراني

| المعلومة | القيمة |
|----------|--------|
| الجهاز | `{hostname}` |
| وقت التقرير | `{now}` |
| مستوى الخطر | **{level_label}** |
| نقاط الخطر | `{score}` |
| إجمالي النتائج | `{len(all_findings)}` |

---

## 📊 ملخص النتائج

| المستوى | العدد |
|---------|-------|
| 🔴 خطير جداً | {counts.get('critical', 0)} |
| 🟠 خطير | {counts.get('high', 0)} |
| 🟡 متوسط | {counts.get('medium', 0)} |
| 🔵 منخفض | {counts.get('low', 0)} |
| ⚪ معلومات | {counts.get('info', 0)} |

---

"""
    else:
        report = f"""# 🛡️ AI AYFAM Cybersecurity Report

| Field | Value |
|-------|-------|
| Host | `{hostname}` |
| Timestamp | `{now}` |
| Risk Level | **{level_label}** |
| Risk Score | `{score}` |
| Total Findings | `{len(all_findings)}` |

---

## 📊 Findings Summary

| Severity | Count |
|----------|-------|
| 🔴 Critical | {counts.get('critical', 0)} |
| 🟠 High | {counts.get('high', 0)} |
| 🟡 Medium | {counts.get('medium', 0)} |
| 🔵 Low | {counts.get('low', 0)} |
| ⚪ Info | {counts.get('info', 0)} |

---

"""

    ordered_sevs = ["critical", "high", "medium", "low", "info"]
    for sev in ordered_sevs:
        sev_findings = [f for f in all_findings if f.get("severity", "").lower() == sev]
        if not sev_findings:
            continue
        icon = _sev_icon(sev)
        if language == "ar":
            sev_names = {"critical": "خطير جداً", "high": "خطير", "medium": "متوسط", "low": "منخفض", "info": "معلومات"}
            report += f"## {icon} النتائج {sev_names.get(sev, sev)} ({len(sev_findings)})\n\n"
        else:
            report += f"## {icon} {sev.upper()} Findings ({len(sev_findings)})\n\n"

        for i, finding in enumerate(sev_findings, 1):
            title = finding.get("title", "")
            detail = finding.get("detail", "")
            fix = finding.get("fix", "")
            if language == "ar":
                report += f"### {i}. {title}\n\n"
                if detail:
                    report += f"**التفاصيل:** {detail}\n\n"
                if fix:
                    report += f"**الحل المقترح:**\n```bash\n{fix}\n```\n\n"
            else:
                report += f"### {i}. {title}\n\n"
                if detail:
                    report += f"**Details:** {detail}\n\n"
                if fix:
                    report += f"**Suggested Fix:**\n```bash\n{fix}\n```\n\n"
            report += "---\n\n"

    for section_name, section_data in sections.items():
        if language == "ar":
            report += f"## 📁 {section_name}\n\n"
        else:
            report += f"## 📁 {section_name}\n\n"
        if isinstance(section_data, dict):
            report += "```json\n" + json.dumps(section_data, ensure_ascii=False, indent=2, default=str)[:2000] + "\n```\n\n"
        elif isinstance(section_data, list):
            for item in section_data[:20]:
                if isinstance(item, dict):
                    report += f"- {json.dumps(item, ensure_ascii=False, default=str)[:200]}\n"
                else:
                    report += f"- {item}\n"
            report += "\n"
        else:
            report += f"{section_data}\n\n"

    if language == "ar":
        report += f"""---

## 🤖 عن AI AYFAM

**AI AYFAM** هو وكيل أمن سيبراني ذكي متخصص يعمل في سطر الأوامر (CLI) على Linux Mint.
يقوم بتحليل شامل للنظام دون الحاجة لاتصال بخدمات ذكاء اصطناعي خارجية.

- 📅 تاريخ التقرير: `{now}`
- 🏠 الجهاز: `{hostname}`
- 🔗 GitHub: https://github.com/AYFAM-Security/AI-AYFAM

*تم إنشاء هذا التقرير تلقائياً بواسطة AI AYFAM*
"""
    else:
        report += f"""---

## 🤖 About AI AYFAM

**AI AYFAM** is an intelligent CLI cybersecurity agent specialized for Linux Mint.
It performs comprehensive system analysis without requiring external AI services.

- 📅 Report Date: `{now}`
- 🏠 Host: `{hostname}`
- 🔗 GitHub: https://github.com/AYFAM-Security/AI-AYFAM

*This report was automatically generated by AI AYFAM*
"""

    return report


def save_report(content: str, report_dir: str, format: str = "md") -> str:
    Path(report_dir).mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"ayfam_report_{timestamp}.{format}"
    filepath = os.path.join(report_dir, filename)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
    return filepath


def generate_json_report(scan_results: dict, hostname: str = "unknown") -> str:
    report = {
        "agent": "AI AYFAM",
        "version": "1.0.0",
        "hostname": hostname,
        "timestamp": datetime.now().isoformat(),
        "risk": scan_results.get("risk", {}),
        "findings": scan_results.get("findings", []),
        "sections": scan_results.get("sections", {}),
    }
    return json.dumps(report, ensure_ascii=False, indent=2, default=str)
